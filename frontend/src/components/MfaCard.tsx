import { useQuery } from "@tanstack/react-query";
import { KeyRound } from "lucide-react";
import { api } from "../api/client";

interface MfaSetup {
  issuer: string;
  account: string;
  otpauth_uri: string;
  qr_svg: string;
}

/**
 * Demo mode only: the approver's own authenticator enrollment QR, so it can be scanned with a
 * phone on stage. The server returns 404 outside demo mode or for any other role.
 */
export function MfaCard() {
  const q = useQuery({ queryKey: ["mfa-setup"], queryFn: () => api<MfaSetup>("/auth/mfa-setup"), retry: false });
  if (!q.data) return null;
  return (
    <section className="panel mfa-card" aria-labelledby="mfa-title">
      {/* The SVG is generated by our own server from the user's own TOTP URI (no user content). */}
      <div className="mfa-qr" aria-label="Authenticator QR code" dangerouslySetInnerHTML={{ __html: q.data.qr_svg }} />
      <div>
        <h2 id="mfa-title" className="label">
          <KeyRound size={13} aria-hidden="true" /> Your authenticator (demo)
        </h2>
        <p>
          Scan with Google Authenticator, Microsoft Authenticator or any TOTP app. Approving an invoice above ₹10 lakh
          asks for the 6-digit code.
        </p>
        <p className="muted">
          Account {q.data.account}. Shown only in demo mode; a production deployment would enroll through the company
          identity provider.
        </p>
      </div>
    </section>
  );
}
